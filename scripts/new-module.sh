#!/usr/bin/env bash
# Creates the skeleton of a module in modules/<id>/: a crate that compiles, with one route
# and a test for it, and a web folder with one page in the project navigation. Then prints
# the three lines that register it. See docs/modules.md.
#
#   scripts/new-module.sh <id> "<Name>"
#   scripts/new-module.sh notes "Release notes"

set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: scripts/new-module.sh <id> \"<Name>\"" >&2
  exit 2
fi

id="$1"
name="$2"

# The id becomes a Rust crate name, a URL segment, a table prefix and a CSS prefix.
if ! [[ "$id" =~ ^[a-z][a-z0-9]{1,19}$ ]]; then
  echo "The id is 2 to 20 lower-case letters and digits, starting with a letter: \"$id\" is not." >&2
  exit 2
fi

if [[ "$name" == *\"* || "$name" == *\'* || "$name" == *\\* || -z "$name" ]]; then
  echo "The name is plain text without quotes or backslashes." >&2
  exit 2
fi

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
dir="$root/modules/$id"
pascal="${id^}"

if [ -e "$dir" ]; then
  echo "modules/$id already exists." >&2
  exit 1
fi

mkdir -p "$dir/src" "$dir/tests" "$dir/web"

cat > "$dir/Cargo.toml" <<EOF
[package]
name = "hub-mod-$id"
version.workspace = true
edition.workspace = true
publish.workspace = true

[dependencies]
hub-core.workspace = true
hub-app.workspace = true
axum.workspace = true
serde.workspace = true
ts-rs.workspace = true

[dev-dependencies]
serde_json.workspace = true
tokio.workspace = true
tower = { version = "0.5", features = ["util"] }
http-body-util = "0.1"
EOF

cat > "$dir/src/lib.rs" <<EOF
//! $name: say here, in a sentence or two, what the module adds to the tracker.

mod routes;
pub mod types;

use axum::Router;
use hub_app::{App, Module, ModuleMeta};

pub struct ${pascal}Module;

impl Module for ${pascal}Module {
    fn meta(&self) -> ModuleMeta {
        ModuleMeta {
            id: "$id",
            name: "$name",
            description: "What the module adds, in one sentence; shown in Settings → Modules.",
            version: env!("CARGO_PKG_VERSION"),
            depends_on: &[],
            default_enabled: true,
        }
    }

    fn routes(&self) -> Option<Router<App>> {
        Some(routes::routes())
    }
}
EOF

cat > "$dir/src/types.rs" <<EOF
//! What the module's routes answer with. TypeScript bindings are generated by \`cargo test\`.

use hub_core::Id;
use serde::Serialize;
use ts_rs::TS;

#[derive(Debug, Clone, PartialEq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct ${pascal}Summary {
    pub project_id: Id,
    pub project_key: String,
    pub open_issues: i64,
}
EOF

cat > "$dir/src/routes.rs" <<EOF
//! Routes under \`/api/m/$id\`. Handlers are thin: the work runs on the worker pool.

use axum::extract::{Path, State};
use axum::routing::get;
use axum::{Json, Router};
use hub_app::access::project_access;
use hub_app::{ApiResult, App, AuthUser};

use crate::types::${pascal}Summary;

pub fn routes() -> Router<App> {
    Router::new().route("/projects/{key}/summary", get(summary))
}

async fn summary(State(app): State<App>, user: AuthUser, Path(key): Path<String>) -> ApiResult<Json<${pascal}Summary>> {
    app.run(move |app| {
        app.read(|connection| {
            let access = project_access(connection, &user, &key)?;
            let open_issues = connection.query_row(
                "SELECT count(*) FROM issue i JOIN status s ON s.id = i.status_id WHERE i.project_id = ?1 AND s.category != 'done'",
                [access.id],
                |row| row.get(0),
            )?;

            Ok(${pascal}Summary { project_id: access.id, project_key: access.key, open_issues })
        })
    })
    .await
    .map(Json)
}
EOF

cat > "$dir/tests/api.rs" <<EOF
use std::sync::atomic::{AtomicU32, Ordering};
use std::sync::Arc;

use axum::body::Body;
use axum::http::{header, Request, StatusCode};
use axum::Router;
use http_body_util::BodyExt;
use hub_app::services::issues::create_issue;
use hub_app::services::projects::{create_project, NewProject};
use hub_app::services::users::{create_token, create_user, NewUser};
use hub_app::{Actor, App, AuthUser, Config, Module};
use hub_core::{IssuePatch, NewIssue, Role};
use hub_mod_$id::${pascal}Module;
use serde_json::Value;
use tower::ServiceExt;

static NEXT: AtomicU32 = AtomicU32::new(0);

/// An application with only this module, mounted where the server mounts it, one project
/// with two open issues, and the token of its administrator.
fn world() -> (Router, String) {
    let directory = std::env::temp_dir().join(format!("team-hub-$id-{}-{}", std::process::id(), NEXT.fetch_add(1, Ordering::Relaxed)));
    let _ = std::fs::remove_dir_all(&directory);
    let app = App::new(Config::for_tests(directory), vec![Arc::new(${pascal}Module)]).expect("the test application starts");

    let new =
        NewUser { name: "Ada Admin".to_string(), email: "ada@example.com".to_string(), password: None, role: Some(Role::Admin), github_login: None };
    let (user, token) = app
        .db
        .write(|tx| {
            let user = create_user(tx, &new)?;
            let token = create_token(tx, user.id, "tests")?;

            Ok((user, token))
        })
        .expect("a user with a token");
    let admin = AuthUser { id: user.id, name: user.name, email: user.email, role: Role::Admin, via_token: true };

    app.write(Actor::user(admin.id), |tx| {
        let project = NewProject {
            key: "DEMO".to_string(),
            name: "Demo".to_string(),
            description: String::new(),
            board_mode: None,
            is_private: false,
            lead_id: None,
        };
        create_project(tx, &admin, &project)?;

        for summary in ["First", "Second"] {
            let fields = IssuePatch { summary: Some(summary.to_string()), ..Default::default() };
            create_issue(tx, &NewIssue { project_key: "DEMO".to_string(), fields })?;
        }

        Ok(())
    })
    .expect("a project with issues");

    let router = Router::new().nest("/api/m/$id", ${pascal}Module.routes().expect("the module has routes")).with_state(app);

    (router, token)
}

async fn get(router: &Router, token: Option<&str>, path: &str) -> (StatusCode, Value) {
    let mut request = Request::builder().uri(format!("/api/m/$id{path}"));

    if let Some(token) = token {
        request = request.header(header::AUTHORIZATION, format!("Bearer {token}"));
    }

    let response = router.clone().oneshot(request.body(Body::empty()).expect("a valid request")).await.expect("the router answers");
    let status = response.status();
    let bytes = response.into_body().collect().await.expect("a readable body").to_bytes();

    (status, serde_json::from_slice(&bytes).unwrap_or(Value::Null))
}

#[tokio::test(flavor = "multi_thread")]
async fn the_summary_counts_the_open_issues_of_a_project() {
    let (router, token) = world();

    let (status, summary) = get(&router, Some(&token), "/projects/demo/summary").await;
    assert_eq!(status, StatusCode::OK, "{summary}");
    assert_eq!(summary["projectKey"], "DEMO");
    assert_eq!(summary["openIssues"], 2);

    assert_eq!(get(&router, Some(&token), "/projects/NOPE/summary").await.0, StatusCode::NOT_FOUND);
    assert_eq!(get(&router, None, "/projects/DEMO/summary").await.0, StatusCode::UNAUTHORIZED);
}
EOF

cat > "$dir/web/index.tsx" <<EOF
import { api } from '@/api.ts';
import type { ${pascal}Summary } from '@/bindings/${pascal}Summary.ts';
import { Empty, ErrorNote, Spinner } from '@/components/ui.tsx';
import { countOf, t } from '@/i18n/index.ts';
import type { WebModule } from '@/modules.ts';
import { changesIssues, useProject, useRemote } from '@/session.tsx';

import { polish } from './pl.ts';
import './styles.css';

function ${pascal}View() {
  const project = useProject();
  const summary = useRemote(() => api.get<${pascal}Summary>(\`/api/m/$id/projects/\${project.key}/summary\`), [project.key], changesIssues);

  return (
    <div className="view">
      <header className="view-head">
        <div>
          <h1>{t('$name')}</h1>
          <p className="muted">{project.name}</p>
        </div>
      </header>
      {summary.error && <ErrorNote message={summary.error} />}
      {!summary.data && !summary.error && <Spinner />}
      {summary.data && (
        <section className="panel $id-summary">
          <Empty icon="puzzle" title={countOf(summary.data.openIssues, 'open issue', 'open issues')}>
            {t('This page comes from the “{name}” module. Replace it with what the module shows.', { name: t('$name') })}
          </Empty>
        </section>
      )}
    </div>
  );
}

export const ${id}Module: WebModule = {
  id: '$id',
  projectNav: (projectKey) => [{ id: '$id', label: () => t('$name'), icon: 'puzzle', path: \`/p/\${projectKey}/$id\` }],
  routes: [{ pattern: '/p/:key/$id', render: () => <${pascal}View /> }],
  polish,
};
EOF

cat > "$dir/web/pl.ts" <<EOF
/** Polish for the phrases of the "$name" module; the key is the English text. */
export const polish: Record<string, string> = {
  '$name': '$name',
  'This page comes from the “{name}” module. Replace it with what the module shows.': 'Ta strona pochodzi z modułu „{name}”. Zastąp ją tym, co moduł ma pokazywać.',
};
EOF

cat > "$dir/web/styles.css" <<EOF
/* $name. Class names start with the module's id. */

.$id-summary {
  padding: 24px;
}
EOF

# The same text \`cargo test\` generates from src/types.rs, so the screens typecheck before the first test run.
cat > "$root/web/src/bindings/${pascal}Summary.ts" <<EOF
// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.

export type ${pascal}Summary = { projectId: number, projectKey: string, openIssues: number, };
EOF

cat > "$dir/README.md" <<EOF
# $id

$name: say here what the module adds.

Crate \`hub-mod-$id\`, \`pub struct ${pascal}Module;\`, id \`$id\`, enabled by default.
No tables, no background work, no events (yet).

## Routes

All under \`/api/m/$id\`, for signed-in callers who may see the project.

### \`GET /projects/{key}/summary\`

\`${pascal}Summary\` (\`web/src/bindings/${pascal}Summary.ts\`): the project and how many of its
issues are open.

## Screens

\`web/index.tsx\` exports \`${id}Module\`: one entry in the project navigation and the page
behind it (\`/p/:key/$id\`). Polish in \`web/pl.ts\`, styles in \`web/styles.css\`.
EOF

# How long a line gets depends on the id; let rustfmt have the last word where it is installed.
(cd "$root" && cargo fmt -p "hub-mod-$id" > /dev/null 2>&1) || true

cat <<EOF
Created modules/$id (crate hub-mod-$id, web module ${id}Module).

Register it in three places:

  crates/hub-server/Cargo.toml, under [dependencies]:
      hub-mod-$id = { path = "../../modules/$id" }

  crates/hub-server/src/lib.rs, in modules():
      Arc::new(hub_mod_$id::${pascal}Module),

  web/src/modules.ts, next to the other modules:
      import { ${id}Module } from '../../modules/$id/web/index.tsx';
      (and add ${id}Module to the list)

Then:

  cargo test -p hub-mod-$id -p hub-server   # also writes the module's types to web/src/bindings/
  (cd web && npm run build)   # boundaries, types, bundle
EOF
